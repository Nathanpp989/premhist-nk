"""gen_glyph_catalog.py - one source for the equipment glyph catalog, three copies generated.

The 90 glyphs and their ten properties each - area, catalog name, class, default size, floor,
absolute floor, words, states, class fields, bindings, ports - are carried three times:

    orchestrator/display_glyphs.py     Describe's copy  (THE SOURCE, from here on)
    ph-types/glyphs.rs                 the server's copy
    display_glyphs_*.js                the viewer's copy

They were reconciled by hand, and the only record of the last check is a comment dated
2026-10-20. Drift means Describe draws a symbol the viewer renders differently, sizes it against
a floor the server rejects, or attaches a pipe to a glyph that has no connection points - and no
test anywhere would notice, because each copy only ever checks itself.

    python tools/gen_glyph_catalog.py --out build/            write glyphs.json, .rs and .js
    python tools/gen_glyph_catalog.py --check build/          fail (exit 1) if they have drifted
    python tools/gen_glyph_catalog.py --summary               what the catalog holds, no files

`--check` is the CI step. It regenerates into memory and diffs; a drifted copy is named, with the
first differing line. It needs nothing but this file, the Python catalog and a standard library.

glyphs.json is the interchange both other copies should ultimately LOAD rather than restate. The
generated .rs and .js are a starting point for that move: they will not match the existing files'
hand-written shape, so the first adoption needs a human pass. The JSON and the checker are the
durable part and work on their own.
"""

from __future__ import annotations

import argparse
import difflib
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
# The catalog lives in the orchestrator package, beside the Describe engines.
for cand in (os.path.join(HERE, "..", "describe"), os.path.join(HERE, ".."), HERE):
    if os.path.isdir(os.path.join(os.path.abspath(cand), "orchestrator")):
        sys.path.insert(0, os.path.abspath(cand))
        break

try:
    from orchestrator import display_glyphs as dg
except Exception as e:                                   # noqa: BLE001
    print(f"cannot import orchestrator.display_glyphs: {type(e).__name__}: {e}", file=sys.stderr)
    print("run this from the install folder, or pass --source <dir containing orchestrator/>",
          file=sys.stderr)
    raise SystemExit(1)

BANNER = "GENERATED by tools/gen_glyph_catalog.py from orchestrator/display_glyphs.py - do not edit"

# Where the port flag comes from. It lives in the catalog from the round that folded it in; in an
# older display_glyphs.py it is still display_pipes' own list. This tool must work against both,
# because the tools folder and the orchestrator package are copied separately and can skew - and
# when they do, the failure was an AttributeError deep inside catalog(), which says nothing about
# which file is out of date.
_PORTLESS_FROM = "catalog"


def _portless() -> frozenset:
    global _PORTLESS_FROM
    got = getattr(dg, "PORTLESS_GLYPHS", None)
    if got is not None:
        _PORTLESS_FROM = "catalog"
        return frozenset(got)
    try:
        from orchestrator import display_pipes as dp
        _PORTLESS_FROM = "display_pipes (this display_glyphs.py predates the catalog's own copy)"
        return frozenset(dp.PORTLESS_GLYPHS)
    except Exception:
        _PORTLESS_FROM = "nothing - assuming every glyph has ports"
        return frozenset()


def preflight() -> int:
    """Is the catalog this tool is pointed at new enough to generate from? Names the file and the
    missing piece rather than failing with an AttributeError three calls deep."""
    need = ["GLYPHS", "GLYPH_AREA", "GLYPH_CATALOG_NAMES", "GLYPH_CLASS", "GLYPH_WORDS",
            "EQUIPMENT_SIZES", "EQUIPMENT_FLOORS", "EQUIPMENT_ABS_FLOORS", "AREAS", "CLASSES",
            "glyph_states", "glyph_fields", "glyph_bind_max", "binding_need", "SECOND_BINDING"]
    missing = [n for n in need if not hasattr(dg, n)]
    if missing:
        print(f"the catalog at {getattr(dg, '__file__', '?')}", file=sys.stderr)
        print(f"is missing: {', '.join(missing)}", file=sys.stderr)
        print("\nThat file is older than this tool expects. The tools folder and the orchestrator",
              file=sys.stderr)
        print("package are copied separately, so they can end up at different versions.",
              file=sys.stderr)
        print("Fix: re-run apply-patch.ps1 from the latest patch bundle, which updates both.",
              file=sys.stderr)
        return 2
    return 0


def catalog() -> dict:
    """Every per-glyph fact, in one shape. Sorted, so the output is byte-stable."""
    portless = _portless()
    glyphs = []
    for g in dg.GLYPHS:
        glyphs.append({
            "id": g,
            "area": dg.GLYPH_AREA[g],
            "catalog_name": dg.GLYPH_CATALOG_NAMES[g],
            "class": dg.GLYPH_CLASS[g],
            "words": dg.GLYPH_WORDS[g],
            "default": list(dg.EQUIPMENT_SIZES[g]),
            "floor": list(dg.EQUIPMENT_FLOORS[g]),
            "abs_floor": list(dg.EQUIPMENT_ABS_FLOORS[g]),
            "states": list(dg.glyph_states(g)),
            "fields": sorted(dg.glyph_fields(g)),
            "bindings": dg.glyph_bind_max(g),
            "binding_need": list(dg.binding_need(g) or []),
            "second_binding": dg.SECOND_BINDING.get(g),
            "ports": g not in portless,
            "requires_range": dg.glyph_requires_range(g),
        })
    return {
        "_comment": BANNER,
        "grid": dg.GRID,
        "areas": [{"id": a, "name": n} for a, n in dg.AREAS],
        "classes": list(dg.CLASSES),
        "class_states": {k: list(v) for k, v in dg.CLASS_STATES.items()},
        "sync_glyphs": list(dg.SYNC_GLYPHS),
        "rotations": list(dg.ROTATIONS),
        "glyphs": glyphs,
    }


def as_json(cat: dict) -> str:
    return json.dumps(cat, indent=2, sort_keys=False, ensure_ascii=False) + "\n"


def as_rust(cat: dict) -> str:
    out = [f"// {BANNER}", "",
           "#[derive(Debug, Clone, Copy, PartialEq, Eq)]",
           "pub struct Glyph {",
           "    pub id: &'static str,",
           "    pub area: &'static str,",
           "    pub catalog_name: &'static str,",
           "    pub class: &'static str,",
           "    pub words: &'static str,",
           "    pub default: (u32, u32),",
           "    pub floor: (u32, u32),",
           "    pub abs_floor: (u32, u32),",
           "    pub bindings: u8,",
           "    pub ports: bool,",
           "}", "",
           f"pub const GRID: u32 = {cat['grid']};",
           f"pub const GLYPHS: [Glyph; {len(cat['glyphs'])}] = ["]
    for g in cat["glyphs"]:
        out.append(
            '    Glyph {{ id: "{id}", area: "{area}", catalog_name: "{cn}", class: "{cls}", '
            'words: "{w}", default: ({d0}, {d1}), floor: ({f0}, {f1}), '
            'abs_floor: ({a0}, {a1}), bindings: {b}, ports: {p} }},'.format(
                id=g["id"], area=g["area"], cn=g["catalog_name"].replace('"', '\\"'),
                cls=g["class"], w=g["words"].replace('"', '\\"'),
                d0=g["default"][0], d1=g["default"][1], f0=g["floor"][0], f1=g["floor"][1],
                a0=g["abs_floor"][0], a1=g["abs_floor"][1], b=g["bindings"],
                p="true" if g["ports"] else "false"))
    out += ["];", ""]
    return "\n".join(out)


def as_js(cat: dict) -> str:
    rows = ",\n".join(
        "  {id}: {{ area: {area}, name: {cn}, cls: {cls}, words: {w}, "
        "def: [{d0}, {d1}], floor: [{f0}, {f1}], absFloor: [{a0}, {a1}], "
        "binds: {b}, ports: {p}, states: {st} }}".format(
            id=json.dumps(g["id"]), area=json.dumps(g["area"]),
            cn=json.dumps(g["catalog_name"]), cls=json.dumps(g["class"]),
            w=json.dumps(g["words"]),
            d0=g["default"][0], d1=g["default"][1], f0=g["floor"][0], f1=g["floor"][1],
            a0=g["abs_floor"][0], a1=g["abs_floor"][1], b=g["bindings"],
            p="true" if g["ports"] else "false", st=json.dumps(g["states"]))
        for g in cat["glyphs"])
    return (f"// {BANNER}\n"
            f"export const GRID = {cat['grid']};\n"
            "export const GLYPH_CATALOG = {\n" + rows + "\n};\n"
            "export const PORTLESS = Object.keys(GLYPH_CATALOG)"
            ".filter((g) => !GLYPH_CATALOG[g].ports);\n"
            "export function ports(g) { return !!(GLYPH_CATALOG[g] && GLYPH_CATALOG[g].ports); }\n")


FILES = {"glyphs.json": as_json, "glyphs.generated.rs": as_rust,
         "glyph_catalog.generated.js": as_js}


def audit() -> list:
    """Is the catalog internally consistent? Returns a list of problems, empty when clean.

    This matters more now than it did: the Python table is the SOURCE the others are generated
    from, so a mistake edited into it is a mistake shipped to all three. Nothing else checks it -
    the tables are built by hand, cross-reference each other by glyph id, and a typo in any of
    the half-dozen derived sets (SECOND_BINDING, PORTLESS_GLYPHS, SYNC_GLYPHS, the field sets)
    names a glyph that may not exist, with no error at import.

    Needs nothing but the Python catalog, so it runs wherever the generator does."""
    bad: list = []
    ids = list(dg.GLYPHS)
    areas = {a for a, _n in dg.AREAS}

    seen: dict = {}
    for g in ids:
        if g in seen:
            bad.append(f"duplicate glyph id: {g}")
        seen[g] = True
    for g in ids:
        if dg.GLYPH_AREA[g] not in areas:
            bad.append(f"{g}: area {dg.GLYPH_AREA[g]!r} is not one of the declared areas")
        if dg.GLYPH_CLASS[g] not in dg.CLASSES:
            bad.append(f"{g}: class {dg.GLYPH_CLASS[g]!r} is not one of CLASSES")
        if not str(dg.GLYPH_WORDS[g]).strip():
            bad.append(f"{g}: empty words")
        if not str(dg.GLYPH_CATALOG_NAMES[g]).strip():
            bad.append(f"{g}: empty catalog name")
        d, f, a = dg.EQUIPMENT_SIZES[g], dg.EQUIPMENT_FLOORS[g], dg.EQUIPMENT_ABS_FLOORS[g]
        for label, box in (("default", d), ("floor", f), ("abs floor", a)):
            if len(box) != 2 or any((not isinstance(v, int)) or v <= 0 for v in box):
                bad.append(f"{g}: {label} {box!r} is not two positive integers")
        if f[0] > d[0] or f[1] > d[1]:
            bad.append(f"{g}: floor {f} is larger than the default size {d}")
        if a[0] > f[0] or a[1] > f[1]:
            bad.append(f"{g}: absolute floor {a} is larger than the floor {f}")
        if a[0] % dg.GRID or a[1] % dg.GRID:
            bad.append(f"{g}: absolute floor {a} is not on the {dg.GRID} px grid")

    # The catalog name and the words are how a model's text reaches a glyph. A name that does not
    # resolve BACK to its own glyph is unreachable through that spelling.
    for g in ids:
        for label, text in (("catalog name", dg.GLYPH_CATALOG_NAMES[g]), ("words", dg.GLYPH_WORDS[g])):
            got = dg.glyph_of(text)
            if got != g:
                bad.append(f"{g}: its {label} {text!r} resolves to {got!r}, not to itself")

    # Every derived set must name glyphs that exist.
    for name, members in (("SECOND_BINDING", dg.SECOND_BINDING), ("PORTLESS_GLYPHS", _portless()),
                          ("SYNC_GLYPHS", dg.SYNC_GLYPHS), ("RANGE_GLYPHS", dg.RANGE_GLYPHS),
                          ("LIMITS_GLYPHS", dg.LIMITS_GLYPHS), ("LETTERS_GLYPHS", dg.LETTERS_GLYPHS),
                          ("VESSEL_GLYPHS", dg.VESSEL_GLYPHS)):
        for g in members:
            if g not in dg.GLYPH_AREA:
                bad.append(f"{name} names {g!r}, which is not a glyph in the catalog")
    for g in dg.SECOND_BINDING:
        if dg.glyph_bind_max(g) != 2:
            bad.append(f"{g}: in SECOND_BINDING but glyph_bind_max says {dg.glyph_bind_max(g)}")
    for g in ids:
        if dg.glyph_bind_max(g) == 2 and g not in dg.SECOND_BINDING:
            bad.append(f"{g}: takes two bindings but is not in SECOND_BINDING")
    for cls in dg.CLASS_STATES:
        if cls not in dg.CLASSES:
            bad.append(f"CLASS_STATES names class {cls!r}, which is not one of CLASSES")
    for v in dg.GLYPH_ALIASES.values():
        if v not in dg.GLYPH_AREA:
            bad.append(f"GLYPH_ALIASES points at {v!r}, which is not a glyph in the catalog")

    # A glyph that requires a min/max range must be able to carry one.
    for g in ids:
        fields = dg.glyph_fields(g)
        if dg.glyph_requires_range(g) and not {"min", "max"} <= fields:
            bad.append(f"{g}: requires a range but its fields are {sorted(fields)}")
        if dg.glyph_states(g) and "states" not in fields:
            bad.append(f"{g}: has states {dg.glyph_states(g)} but no 'states' field")
    return bad


# Names worth looking at, and the content test that decides it. Searching by NAME alone is not
# enough: nobody knows what the viewer calls its copy, and that is exactly the open question.
# A file is a glyph table if it mentions enough distinctive glyph ids, whatever it is called.
_FIND_EXT = (".rs", ".js", ".ts", ".mjs", ".json")
_FIND_SKIP = {"node_modules", ".git", "__pycache__", "target", "dist", "build", ".venv", "venv"}
_FIND_MIN_HITS = 12
_FIND_MAX_BYTES = 8 * 1024 * 1024


def find_copies(root: str, limit: int = 20000) -> list:
    """Every file under `root` that looks like a copy of the glyph table.

    This exists because "where does the viewer keep its copy?" had no answer, and guessing a
    folder is how a check ends up silently checking nothing. It reads files rather than trusting
    names, so a copy called anything at all is still found."""
    ids = [str(g) for g in dg.GLYPHS]
    probe = [i for i in ids if len(i) > 4][:60] or ids[:60]
    hits: list = []
    looked = 0
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = [d for d in dirnames if d not in _FIND_SKIP and not d.startswith(".")]
        for fn in filenames:
            if not fn.lower().endswith(_FIND_EXT):
                continue
            looked += 1
            if looked > limit:
                return hits
            p = os.path.join(dirpath, fn)
            try:
                if os.path.getsize(p) > _FIND_MAX_BYTES:
                    continue
                with open(p, encoding="utf-8", errors="replace") as f:
                    body = f.read()
            except OSError:
                continue
            n = sum(1 for g in probe if g in body)
            if n >= _FIND_MIN_HITS:
                # Compare by the SET of glyph ids, not byte for byte. A hand-written viewer table
                # will never be byte-identical to the generated form, so a byte diff would read
                # DRIFT for every copy and tell nobody anything. Which glyphs each side knows
                # about is the question that actually matters.
                present = {g for g in ids if _mentions(body, g)}
                hits.append({"path": p, "glyph_ids_seen": n, "bytes": len(body),
                             "ext": os.path.splitext(fn)[1].lower(),
                             "missing": sorted(set(ids) - present),
                             "extra_hint": len(present) - len(set(ids)) if present > set(ids) else 0,
                             "known": len(present)})
    hits.sort(key=lambda h: (-h["known"], h["path"]))
    return hits


def _mentions(body: str, glyph: str) -> bool:
    """`glyph` appears as a whole token, so `pump` does not match inside `pump_house`."""
    return re.search(r"(?<![A-Za-z0-9_])" + re.escape(glyph) + r"(?![A-Za-z0-9_])", body) is not None


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--out", metavar="DIR", help="write the generated files here")
    ap.add_argument("--check", metavar="DIR", help="compare the files there against this catalog")
    ap.add_argument("--summary", action="store_true", help="what the catalog holds; writes nothing")
    ap.add_argument("--audit", action="store_true",
                    help="is the catalog itself consistent? needs no other files")
    ap.add_argument("--find", metavar="DIR", nargs="?", const="", default=None,
                    help="search DIR (default: the install) for other copies of the glyph table, "
                         "by content rather than by filename")
    a = ap.parse_args()
    rc = preflight()
    if rc:
        return rc
    cat = catalog()

    if a.audit:
        problems = audit()
        if problems:
            print(f"{len(problems)} problem(s) in the catalog:")
            for p in problems:
                print(f"  - {p}")
            return 1
        print(f"catalog is self-consistent: {len(cat['glyphs'])} glyphs, "
              f"{len(cat['areas'])} areas, every derived set names a real glyph, every catalog "
              f"name and words string resolves back to its own glyph.")
        if not (a.out or a.check or a.summary):
            return 0

    if a.find is not None:
        root = os.path.abspath(a.find or os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
        if not os.path.isdir(root):
            print(f"no such folder: {root}")
            return 1
        print(f"searching {root} for copies of the glyph table (by content, not by name) ...")
        hits = find_copies(root)
        mine = os.path.abspath(dg.__file__)
        hits = [h for h in hits if os.path.abspath(h["path"]) != mine]
        if not hits:
            print("  none found.")
            print("  So this install carries only the Python catalog, and --check has nothing to")
            print("  compare against here. If the viewer ships its copy somewhere else, point this")
            print("  at it:  --find \"C:\\path\\to\\the\\viewer\"")
            return 0
        total = len(cat["glyphs"])
        drifted = 0
        print(f"  {len(hits)} candidate(s), most complete first:")
        for h in hits:
            print(f"    {h['path']}")
            print(f"      {h['ext']}, {h['bytes']:,} bytes; names {h['known']} of {total} glyphs")
            if h["missing"]:
                drifted += 1
                shown = ", ".join(h["missing"][:10]) + (" ..." if len(h["missing"]) > 10 else "")
                print(f"      MISSING {len(h['missing'])}: {shown}")
            else:
                print("      every glyph in the Python catalog is named here")
        print()
        if drifted:
            print(f"  {drifted} copy/copies do not name every glyph the Python catalog has. That is")
            print("  drift worth looking at: a glyph the viewer does not know is one Describe can")
            print("  draft and the viewer cannot draw.")
        else:
            print("  Every copy names every glyph the Python catalog has.")
        print("  (Compared by which glyph ids each file names, not byte for byte: a hand-written")
        print("   table is never byte-identical to the generated form, and that is not the question.)")
        if not (a.out or a.check or a.summary):
            return 1 if drifted else 0

    if a.summary or not (a.out or a.check):
        by_area: dict = {}
        for g in cat["glyphs"]:
            by_area.setdefault(g["area"], []).append(g["id"])
        print(f"{len(cat['glyphs'])} glyphs, grid {cat['grid']}, {len(cat['areas'])} areas")
        for area in cat["areas"]:
            print(f"  {area['id']:12} {len(by_area.get(area['id'], [])):3}  {area['name']}")
        portless = [g["id"] for g in cat["glyphs"] if not g["ports"]]
        two = [g["id"] for g in cat["glyphs"] if g["bindings"] == 2]
        print(f"  no connection points : {', '.join(portless) or 'none'}"
              f"   [from {_PORTLESS_FROM}]")
        print(f"  two bindings         : {', '.join(two) or 'none'}")
        if not (a.out or a.check):
            return 0

    if a.out:
        os.makedirs(a.out, exist_ok=True)
        for name, fn in FILES.items():
            p = os.path.join(a.out, name)
            with open(p, "w", encoding="utf-8", newline="\n") as f:
                f.write(fn(cat))
            print(f"wrote {p}")
        return 0

    bad = 0
    for name, fn in FILES.items():
        p = os.path.join(a.check, name)
        want = fn(cat)
        if not os.path.isfile(p):
            print(f"DRIFT {name}: not found at {p}")
            bad += 1
            continue
        with open(p, encoding="utf-8") as f:
            got = f.read()
        if got == want:
            print(f"ok    {name}")
            continue
        bad += 1
        print(f"DRIFT {name}: differs from the catalog in display_glyphs.py")
        diff = list(difflib.unified_diff(got.splitlines(), want.splitlines(),
                                         fromfile=f"{name} (on disk)", tofile="(from the catalog)",
                                         lineterm="", n=1))
        for line in diff[:12]:
            print(f"      {line}")
        if len(diff) > 12:
            print(f"      ... {len(diff) - 12} more diff lines")
    if bad:
        print(f"\n{bad} copy/copies have drifted. Regenerate with --out, or fix the catalog.")
        return 1
    print("\nevery generated copy matches the catalog.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
